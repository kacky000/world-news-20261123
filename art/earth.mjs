export function projector(x0, y0, w, h) {
  return (lon, lat) => [x0 + ((lon + 180) / 360) * w, y0 + ((78 - lat) / 128) * h];
}

// pins: [{n, lon, lat, color}]
export function worldMap(x0, y0, w, h, pins, o = {}) {
  const p = projector(x0, y0, w, h);
  const sea = tag('rect', { x: x0, y: y0, width: w, height: h, fill: o.sea ?? '#dfe9ef', rx: 4 });
  const grid = [];
  for (let lon = -150; lon <= 150; lon += 30) {
    const [gx] = p(lon, 0);
    grid.push(tag('line', { x1: gx, y1: y0, x2: gx, y2: y0 + h, stroke: '#c9d7df', stroke_width: 0.6 }));
  }
  for (const lat of [60, 30, 0, -30]) {
    const [, gy] = p(0, lat);
    grid.push(tag('line', { x1: x0, y1: gy, x2: x0 + w, y2: gy, stroke: lat === 0 ? '#b3c5cf' : '#c9d7df', stroke_width: 0.6 }));
  }
  const land = LAND.map((poly) =>
    tag('polygon', {
      points: poly.map(([lo, la]) => p(lo, la).map((v) => v.toFixed(1)).join(',')).join(' '),
      fill: o.land ?? '#f4efe3', stroke: '#a89f8a', stroke_width: 0.7, stroke_linejoin: 'round',
    }),
  );
  const r = o.pin ?? 6.5;
  const dots = pins.map((pin) => {
    const [px, py] = p(pin.lon, pin.lat);
    return tag('g', {},
      tag('circle', { cx: px, cy: py, r, fill: pin.color, stroke: '#fff', stroke_width: 1.2 }),
      line(px, py + 3, pin.n, { size: r * 1.15, weight: 700, fill: '#fff', anchor: 'middle' }),
    );
  });
  return tag('g', {}, sea, grid, land, dots);
}
